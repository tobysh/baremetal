static int BIG;

/* days since 1970-01-01 for a proleptic Gregorian date (independent of the lesson's method) */
static long long ref_days(int y, int m, int d) {
    y -= m <= 2;
    long long era = (y >= 0 ? y : y - 399) / 400;
    long long yoe = y - era * 400;
    long long doy = (153 * (m + (m > 2 ? -3 : 9)) + 2) / 5 + d - 1;
    long long doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    return era * 146097 + doe - 719468;
}

int main(void) {
    for (size_t i = 0; i < sizeof X / sizeof X[0]; i++) {
        char name[64];
        Meta m;
        memset(&m, 0x7e, sizeof m);
        snprintf(name, sizeof name, "photo %zu (%zu bytes)", i + 1, X[i].n);
        int rc = read_meta(X[i].p, X[i].n, &m);
        int ok = rc == X[i].rc;
        if (ok && rc == 0)
            ok = strcmp(m.make, X[i].want.make) == 0 && strcmp(m.model, X[i].want.model) == 0 && m.width == X[i].want.width &&
                 m.height == X[i].want.height && strcmp(m.datetime, X[i].want.datetime) == 0;
        CHECK(name, ok, "expected rc %d, make \"%s\", model \"%s\", %ux%u, taken \"%s\"; got rc %d, make \"%s\", model \"%s\", %ux%u, taken \"%s\"",
              X[i].rc, X[i].want.make, X[i].want.model, X[i].want.width, X[i].want.height, X[i].want.datetime,
              rc, rc == 0 ? m.make : "", rc == 0 ? m.model : "", rc == 0 ? m.width : 0, rc == 0 ? m.height : 0, rc == 0 ? m.datetime : "");
    }
    for (size_t i = 0; i < sizeof T / sizeof T[0]; i++) {
        char name[64];
        snprintf(name, sizeof name, "to_unix(\"%.10s\")", T[i].s);
        long long got = to_unix(T[i].s);
        CHECK(name, got == T[i].want, "expected %lld, got %lld", T[i].want, got);
    }

    /* Extra cases: TIFF data is assembled at run time in either byte order. */
    {
        uint8_t b[400];
        Meta m, m2;
        int rc;
#define W16(p, v) do { unsigned v_ = (v); if (BIG) { (p)[0] = (uint8_t)(v_ >> 8); (p)[1] = (uint8_t)v_; } else { (p)[0] = (uint8_t)v_; (p)[1] = (uint8_t)(v_ >> 8); } } while (0)
#define W32(p, v) do { uint32_t v_ = (v); for (int k_ = 0; k_ < 4; k_++) (p)[BIG ? 3 - k_ : k_] = (uint8_t)(v_ >> (8 * k_)); } while (0)
#define HDR(count) do { memset(b, 0, sizeof b); b[0] = b[1] = BIG ? 'M' : 'I'; W16(b + 2, 42); W32(b + 4, 8); W16(b + 8, (count)); } while (0)
#define ENT(i, tag, type, cnt, val) do { uint8_t *e_ = b + 10 + 12 * (i); W16(e_, (tag)); W16(e_ + 2, (type)); W32(e_ + 4, (cnt)); W32(e_ + 8, (val)); } while (0)
#define ENTS(i, tag, v16) do { uint8_t *e_ = b + 10 + 12 * (i); W16(e_, (tag)); W16(e_ + 2, 3); W32(e_ + 4, 1); W16(e_ + 8, (v16)); } while (0)

        /* the same photo in both byte orders: 5 entries, strings after the directory at 74 */
        for (BIG = 0; BIG <= 1; BIG++) {
            HDR(5);
            ENT(0, 0x010f, 2, 4, 0); memcpy(b + 10 + 8, "Cam", 4);
            ENT(1, 0x0110, 2, 9, 74); memcpy(b + 74, "Pocket 7", 9);
            ENTS(2, 0x0100, 640);
            ENT(3, 0x0101, 4, 1, 480123u);
            ENT(4, 0x0132, 2, 20, 83); memcpy(b + 83, "2024:02:29 23:59:59", 20);
            Meta *dst = BIG ? &m2 : &m;
            memset(dst, 0x7e, sizeof *dst);
            rc = read_meta(b, 103, dst);
            if (rc != 0) break;
        }
        BIG = 0;
        CHECK("the same photo parses in little- and big-endian order", rc == 0 && strcmp(m.make, "Cam") == 0 && strcmp(m.model, "Pocket 7") == 0 && m.width == 640 && m.height == 480123u && strcmp(m.datetime, "2024:02:29 23:59:59") == 0,
              "little-endian: rc %d make \"%s\" model \"%s\" %ux%u taken \"%s\"", rc, m.make, m.model, m.width, m.height, m.datetime);
        CHECK("big-endian result equals the little-endian one", memcmp(m.make, m2.make, 4) == 0 && strcmp(m.model, m2.model) == 0 && m.width == m2.width && m.height == m2.height && strcmp(m.datetime, m2.datetime) == 0,
              "big-endian: make \"%s\" model \"%s\" %ux%u taken \"%s\"", m2.make, m2.model, m2.width, m2.height, m2.datetime);

        /* inline limit: count 4 ("ABC\0") is inline, count 5 ("ABCD\0") is at an offset */
        HDR(2); ENT(0, 0x010f, 2, 4, 0); memcpy(b + 18, "ABC", 4); ENT(1, 0x0110, 2, 5, 50); memcpy(b + 50, "ABCD", 5);
        memset(&m, 0x7e, sizeof m);
        rc = read_meta(b, 60, &m);
        CHECK("strings of 4 bytes are inline, longer ones use the offset", rc == 0 && strcmp(m.make, "ABC") == 0 && strcmp(m.model, "ABCD") == 0, "rc %d make \"%s\" model \"%s\"", rc, m.make, m.model);

        HDR(1); ENTS(0, 0x0100, 1);
        memset(&m, 0x7e, sizeof m);
        rc = read_meta(b, 24, &m);
        CHECK("missing tags are cleared, not left from the caller's buffer", rc == 0 && m.make[0] == 0 && m.model[0] == 0 && m.datetime[0] == 0 && m.width == 1 && m.height == 0, "rc %d make[0]=%d height %u", rc, m.make[0], m.height);

        HDR(3); ENT(0, 0xbeef, 7, 0xffffffffu, 1); ENT(1, 0x0100, 5, 1, 99); ENT(2, 0x0101, 3, 1, 0); W16(b + 10 + 12 * 2 + 8, 77);
        memset(&m, 0x7e, sizeof m);
        rc = read_meta(b, 46, &m);
        CHECK("unknown tags and unsupported types are ignored", rc == 0 && m.width == 0 && m.height == 77, "rc %d width %u height %u (a RATIONAL width must be ignored)", rc, m.width, m.height);

        HDR(1000); ENTS(0, 0x0100, 5);
        CHECK("an entry count larger than the data is malformed", read_meta(b, 100, &m) == -1, "1000 entries in 100 bytes must return -1");
        HDR(1); ENTS(0, 0x0100, 5);
        CHECK("a directory cut off in the middle of an entry is malformed", read_meta(b, 10 + 11, &m) == -1, "n stops one byte before the end of the entry");

        HDR(0);
        CHECK("an empty directory is valid", read_meta(b, 10, &m) == 0 && m.width == 0, "count 0 with n = 10 should be rc 0");
        CHECK("a directory offset with no room for the count is malformed", read_meta(b, 9, &m) == -1, "offset 8 but only 1 byte remains");
        W32(b + 4, 4000);
        CHECK("a directory offset beyond the data is malformed", read_meta(b, 10, &m) == -1, "offset 4000 in 10 bytes");

        HDR(1); ENT(0, 0x0110, 2, 20, 380); memcpy(b + 380, "this is twenty chars", 20);
        CHECK("a string offset beyond the data is malformed", read_meta(b, 390, &m) == -1, "20 bytes at offset 380 end at 400 but n is 390");
        HDR(1); ENT(0, 0x0110, 2, 10, 40); memset(b + 40, 'x', 10);
        CHECK("a string without its terminator is malformed", read_meta(b, 60, &m) == -1, "10 bytes of 'x' with no zero");
        HDR(1); ENT(0, 0x0110, 2, 70, 40); memset(b + 40, 'x', 69); b[109] = 0;
        CHECK("a model longer than its 64-byte field is malformed", read_meta(b, 120, &m) == -1, "count 70 does not fit a 64-byte field");
        HDR(1); ENTS(0, 0x0100, 5); W32(b + 10 + 4, 2);
        CHECK("a numeric tag with count 2 is malformed", read_meta(b, 30, &m) == -1, "width with count 2");

        HDR(0); W16(b + 2, 43);
        CHECK("a magic number other than 42 is rejected", read_meta(b, 10, &m) == -1, "42 was replaced by 43");
        HDR(0); b[0] = 'X'; b[1] = 'X';
        CHECK("an unknown byte order mark is rejected", read_meta(b, 10, &m) == -1, "header starts XX");
        HDR(0);
        CHECK("fewer than eight bytes is rejected", read_meta(b, 7, &m) == -1, "n = 7");

        /* every calendar day from 1970 to 2100 against a reference day count */
        int all_ok = 1;
        char txt[32], first_bad[32] = "";
        long long got = 0, want = 0;
        for (int y = 1970; y <= 2100 && all_ok; y++)
            for (int mo = 1; mo <= 12 && all_ok; mo++)
                for (int d = 1; d <= 31 && all_ok; d++) {
                    int dim = (int[]){31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31}[mo - 1] + (mo == 2 && ((y % 4 == 0 && y % 100 != 0) || y % 400 == 0));
                    snprintf(txt, sizeof txt, "%04d:%02d:%02d 12:34:56", y, mo, d);
                    got = to_unix(txt);
                    want = d <= dim ? ref_days(y, mo, d) * 86400 + 12 * 3600 + 34 * 60 + 56 : -1;
                    if (got != want) { all_ok = 0; snprintf(first_bad, sizeof first_bad, "%s", txt); }
                }
        CHECK("to_unix agrees with a reference for every day 1970-2100", all_ok, "first mismatch at %s: expected %lld, got %lld", first_bad, want, got);

        static const char *const BAD[] = {"", "2026:03:02 09:15:00 ", " 2026:03:02 09:15:00", "2026:03:02 09:15:0", "2026:03:02T09:15:00", "2026/03/02 09:15:00", "2026:3:2 09:15:00", "2026:03:02 9:15:00",
                                          "20a6:03:02 09:15:00", "2101:01:01 00:00:00", "1900:01:01 00:00:00", "2026:00:10 00:00:00", "2026:02:30 00:00:00", "2026:06:31 00:00:00", "2026:03:02 09:15:00x", "2026:03:02 24:00:00"};
        int bad_ok = 1;
        size_t bad_i = 0;
        for (size_t i = 0; i < sizeof BAD / sizeof BAD[0] && bad_ok; i++)
            if (to_unix(BAD[i]) != -1) { bad_ok = 0; bad_i = i; }
        CHECK("malformed or out of range timestamps return -1", bad_ok, "to_unix(\"%s\") should be -1", BAD[bad_i]);
        CHECK("year boundaries", to_unix("2100:12:31 23:59:59") == 4133980799LL && to_unix("1970:01:01 00:00:01") == 1LL && to_unix("2100:03:01 00:00:00") - to_unix("2100:02:28 00:00:00") == 86400,
              "2100 is not a leap year: 02:28 to 03:01 is one day");
    }

    return 0;
}
